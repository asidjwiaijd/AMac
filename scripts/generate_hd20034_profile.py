"""Convert the supplied Rockchip panel DTSI to a checked-in P4 panel profile.

Only display timing, reset delays and DCS initialization data are imported.
RK3566 GPIOs, PWM settings and kernel build instructions do not apply to P4.
"""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "hardware/reference/tspi-rk3566-dsi-v10.dtsi"
OUTPUT = ROOT / "src/board/amac/hd20034_panel_profile.h"


def parse_profile(data):
    text = data.decode("utf-8-sig")
    text = re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)
    block = re.search(r"panel-init-sequence\s*=\s*\[(.*?)\]", text, re.S)
    if not block:
        raise ValueError("panel-init-sequence is missing")
    raw = bytes.fromhex(block.group(1))
    commands = []
    offset = 0
    while offset < len(raw):
        if len(raw) - offset < 3:
            raise ValueError("truncated DSI command header")
        packet, delay, length = raw[offset:offset + 3]
        offset += 3
        if not 1 <= length <= 17 or offset + length > len(raw):
            raise ValueError("invalid DSI payload length")
        payload = raw[offset:offset + length]
        offset += length
        expected_type = 0x05 if length == 1 else 0x15 if length == 2 else 0x39
        if packet != expected_type:
            raise ValueError("packet type does not match a supported DCS write")
        commands.append((payload[0], payload[1:], delay))

    fields = {
        "PixelClockHz": "clock-frequency", "Width": "hactive", "Height": "vactive",
        "HFrontPorch": "hfront-porch", "HBackPorch": "hback-porch", "HSync": "hsync-len",
        "VFrontPorch": "vfront-porch", "VBackPorch": "vback-porch", "VSync": "vsync-len",
        "LaneRateMbps": "rockchip,lane-rate", "DataLanes": "dsi,lanes",
        "PrepareDelayMs": "prepare-delay-ms", "ResetDelayMs": "reset-delay-ms",
        "InitDelayMs": "init-delay-ms", "EnableDelayMs": "enable-delay-ms",
    }
    values = {}
    for name, prop in fields.items():
        match = re.search(r"\b" + re.escape(prop) + r"\s*=\s*<(\d+)>", text)
        if not match:
            raise ValueError(f"missing property: {prop}")
        values[name] = int(match.group(1))
    if not re.search(r"dsi,format\s*=\s*<MIPI_DSI_FMT_RGB888>", text):
        raise ValueError("review the source color-format adaptation")
    values["SourceBitsPerPixel"] = 24
    return values, commands


def render(data):
    values, commands = parse_profile(data)
    lines = [
        "// Generated by scripts/generate_hd20034_profile.py; do not hand-edit.",
        "// Input: hardware/reference/tspi-rk3566-dsi-v10.dtsi",
        "// Input SHA256: " + hashlib.sha256(data).hexdigest(),
        "#pragma once", "#include <stddef.h>", "#include <stdint.h>", "",
        "namespace AmacHd20034 {",
    ]
    for name, value in values.items():
        lines.append(f"static constexpr uint32_t k{name} = {value};")
    lines += ["", "struct Command {", "    uint8_t command;", "    uint8_t data_bytes;",
              "    uint16_t delay_ms;", "    uint8_t data[16];", "};", "",
              "static constexpr Command kInitCommands[] = {"]
    for command, payload, delay in commands:
        params = ", ".join(f"0x{b:02X}" for b in payload) or "0"
        lines.append(f"    {{0x{command:02X}, {len(payload)}, {delay}, {{{params}}}}},")
    lines += ["};", "static constexpr size_t kInitCommandCount =",
              "    sizeof(kInitCommands) / sizeof(kInitCommands[0]);",
              "} // namespace AmacHd20034", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the tracked profile is stale")
    args = parser.parse_args()
    expected = render(SOURCE.read_bytes())
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            parser.exit(1, "HD20034 profile is stale; run this script without --check\n")
        print("HD20034 profile matches the supplied DTSI")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
        print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
